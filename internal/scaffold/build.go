const (
	bridgeNote  = "generated by baker; edit AGENTS.md instead"
	hookCommand = "command -v baker >/dev/null 2>&1 && baker checkpoint --agent %s --quiet || true"
)

// Build plans every file for a project: AGENTS.md, bridges, skills, memory,
// .gitignore, MCP configs, hooks and baker.toml. It is used by new, init and sync.
func Build(p *Plan, proj *config.Project, r *recipe.Recipe) error {
	data := recipe.Data{Name: proj.Name, Facts: proj.Facts}
	enabled := agents.For(proj)

	if err := planAgentsMD(p, proj, r, data, enabled); err != nil {
		return err
	}
	planBridges(p, enabled)
	planSkills(p, r, enabled)
	planMemory(p)
	planGitignore(p, r)
	if err := planMCP(p, proj, enabled); err != nil {
		return err
	}
	for _, a := range enabled {
		if a.HooksFile != "" {
			if err := planHooks(p, a); err != nil {
				return err
			}
		}
	}
	return planManifest(p, proj)
}

func planAgentsMD(p *Plan, proj *config.Project, r *recipe.Recipe, data recipe.Data, enabled []agents.Agent) error {
	if _, exists := p.Read("AGENTS.md"); !exists {
		notes := recipe.Core("notes.md")
		extra, err := r.Render("notes.md", data)
		if err != nil {
			return err
		}
		notes = strings.TrimRight(notes, "\n") + "\n" + extra
		// Adopt instructions that already live in vendor files, so nothing is lost.
		for _, a := range enabled {
			if a.BridgeFile == "" || !strings.HasSuffix(a.BridgeFile, ".md") {
				continue
			}
			if cur, ok := p.Read(a.BridgeFile); ok {
				if user := blocks.Strip(cur, blocks.Markdown); user != "" && user != a.BridgeContent {
					notes += fmt.Sprintf("\n## Imported from %s\n\n%s\n", a.BridgeFile, user)
					p.set(a.BridgeFile, "", "")
					p.Note(a.BridgeFile, "its instructions moved into AGENTS.md")
				}
			}
		}
		p.set("AGENTS.md", "# "+proj.Name+"\n\n"+strings.TrimRight(notes, "\n")+"\n", "")
	}

	recipeBlock, err := r.Render("agents.md", data)
	if err != nil {
		return err
	}
	if strings.TrimSpace(recipeBlock) != "" {
		p.Block("AGENTS.md", "recipe:"+r.Name, fmt.Sprint(r.Version), recipeBlock, "", blocks.Append)
	}
	p.Block("AGENTS.md", "core", config.Standard, recipe.Core("agents.md"), "", blocks.Append)

	if cur, _ := p.Read("AGENTS.md"); len(cur) > 32*1024 {
		p.Warnings = append(p.Warnings, "AGENTS.md is over 32 KiB; Codex truncates it. Move detail into memory notes.")
	}
	return nil
}

func planBridges(p *Plan, enabled []agents.Agent) {
	agentsMD, _ := p.Read("AGENTS.md")
	for _, a := range enabled {
		if a.BridgeFile == "" {
			continue
		}
		// Some skeletons (e.g. Laravel 13) ship CLAUDE.md as a copy of AGENTS.md.
		// Once the bridge imports AGENTS.md, the copy would load twice — drop it.
		if strings.HasSuffix(a.BridgeFile, ".md") {
			if cur, ok := p.Read(a.BridgeFile); ok {
				user := blocks.Strip(cur, blocks.Markdown)
				if user != "" && user != a.BridgeContent && strings.Contains(agentsMD, user) {
					p.set(a.BridgeFile, "", "")
					p.Note(a.BridgeFile, "removed text that duplicated AGENTS.md")
				}
			}
		}
		p.Block(a.BridgeFile, "bridge", "1", a.BridgeContent, bridgeNote, blocks.Prepend)
	}
}

func planSkills(p *Plan, r *recipe.Recipe, enabled []agents.Agent) {
	skills := recipe.CoreSkills()
	for k, v := range r.Skills() {
		skills[k] = v
	}
	keys := make([]string, 0, len(skills))
	for k := range skills {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		p.Managed(path.Join(".agents/skills", k), skills[k])
		for _, a := range enabled {
			if a.SkillsDir != "" {
				p.Managed(path.Join(a.SkillsDir, k), skills[k])
			}
		}
	}
}

func planMemory(p *Plan) {
	p.Once("memory/MEMORY.md", recipe.Core("MEMORY.md"))
	p.Once("memory/hot.md", recipe.Core("hot.md"))
	for _, d := range []string{"log", "decisions", "lessons", "knowledge"} {
		if _, ok := p.Read("memory/" + d + "/.gitkeep"); !ok && !p.dirHasFiles("memory/"+d) {
			p.Once("memory/"+d+"/.gitkeep", "")
		}
	}
}

func planGitignore(p *Plan, r *recipe.Recipe) {
	lines := []string{"memory/hot.md", ".baker/checkpoints/", ".baker/graph/"}
	lines = append(lines, r.Gitignore...)
	p.Block(".gitignore", "baker", "1", strings.Join(lines, "\n"), "", blocks.Append)
}

func planMCP(p *Plan, proj *config.Project, enabled []agents.Agent) error {
	want := map[string]config.MCPServer{}
	for _, s := range proj.MCP {
		want[s.Name] = s
	}
	stale := []string{}
	for _, n := range p.Lock.MCP {
		if _, ok := want[n]; !ok {
			stale = append(stale, n)
		}
	}
	if len(want) == 0 && len(stale) == 0 {
		return nil
	}
	for _, a := range enabled {
		if a.MCPFile == "" {
			continue
		}
		switch a.MCPFormat {
		case agents.MCPServers, agents.MCPVSCode, agents.MCPOpenCode:
			key := map[agents.MCPFormat]string{agents.MCPServers: "mcpServers", agents.MCPVSCode: "servers", agents.MCPOpenCode: "mcp"}[a.MCPFormat]
			format := a.MCPFormat
			err := p.JSON(a.MCPFile, func(doc map[string]any) {
				servers, _ := doc[key].(map[string]any)
				if servers == nil {
					servers = map[string]any{}
				}
				for _, n := range stale {
					delete(servers, n)
				}
				for n, s := range want {
					servers[n] = mcpEntry(format, s)
				}
				if len(servers) == 0 {
					delete(doc, key)
				} else {
					doc[key] = servers
				}
			})
			if err != nil {
				return err
			}
		case agents.MCPCodexTOML:
			tables := map[string]any{}
			for n, s := range want {
				t := map[string]any{"command": s.Command}
				if len(s.Args) > 0 {
					t["args"] = s.Args
				}
				if len(s.Env) > 0 {
					t["env"] = s.Env
				}
				tables[n] = t
			}
			b, err := toml.Marshal(map[string]any{"mcp_servers": tables})
			if err != nil {
				return err
			}
			p.Block(a.MCPFile, "mcp", "1", string(b), "", blocks.Append)
		}
	}
	names := make([]string, 0, len(want))
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)
	p.Lock.MCP = names
	return nil
}

func mcpEntry(f agents.MCPFormat, s config.MCPServer) map[string]any {
	e := map[string]any{}
	switch f {
	case agents.MCPOpenCode:
		e["type"] = "local"
		e["command"] = append([]string{s.Command}, s.Args...)
		if len(s.Env) > 0 {
			e["environment"] = s.Env
		}
		return e
	case agents.MCPVSCode:
		e["type"] = "stdio"
	}
	e["command"] = s.Command
	if len(s.Args) > 0 {
		e["args"] = s.Args
	}
	if len(s.Env) > 0 {
		e["env"] = s.Env
	}
	return e
}

// planHooks registers `baker checkpoint` on an agent's hook events: Stop and
// PreCompact for Claude Code, AfterAgent and PreCompress for Gemini CLI. Both
// pass {transcript_path, cwd} on stdin and use the same settings shape.
func planHooks(p *Plan, a agents.Agent) error {
	return p.JSON(a.HooksFile, func(doc map[string]any) {
		hooks, _ := doc["hooks"].(map[string]any)
		if hooks == nil {
			hooks = map[string]any{}
		}
		for _, event := range a.HookEvents {
			list, _ := hooks[event].([]any)
			if hasBakerHook(list) {
				continue
			}
			list = append(list, map[string]any{
				"hooks": []any{map[string]any{"type": "command", "command": fmt.Sprintf(hookCommand, a.ID)}},
			})
			hooks[event] = list
		}
		doc["hooks"] = hooks
	})
}

func hasBakerHook(list []any) bool {
	for _, item := range list {
		m, _ := item.(map[string]any)
		inner, _ := m["hooks"].([]any)
		for _, h := range inner {
			hm, _ := h.(map[string]any)
			if cmd, _ := hm["command"].(string); strings.Contains(cmd, "baker checkpoint") {
				return true
			}
		}
	}
	return false
}

func planManifest(p *Plan, proj *config.Project) error {
	b, err := toml.Marshal(proj)
	if err != nil {
		return err
	}
	header := "# baker project manifest — https://github.com/roguenet/baker\n# Edit agents or mcp here, then run `baker sync`.\n\n"
	cur, exists := p.Read(config.ProjectFile)
	if exists {
		var old config.Project
		if toml.Unmarshal([]byte(cur), &old) == nil {
			if nb, _ := toml.Marshal(&old); string(nb) == string(b) {
				return nil
			}
		}
	}
	p.set(config.ProjectFile, header+string(b), "")
	return nil
}
